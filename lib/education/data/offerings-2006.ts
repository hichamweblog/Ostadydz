import { SOURCES } from '../sources';
import type { HoursDef, LevelCode, OfferingDef, StreamId, SubjectId, VariantId, VerificationStatus } from '../types';

function makeOffering(params: {
  levelCode: LevelCode;
  streamId: StreamId;
  subjectId: SubjectId;
  variantId?: VariantId;
  optional?: boolean;
  coefficient: number | null;
  hours: HoursDef | null;
  schemeId: string;
  coefVer?: VerificationStatus;
  hoursVer?: VerificationStatus;
  schemeVer?: VerificationStatus;
  notes?: string;
}): OfferingDef {
  return {
    frameworkId: 'DZ_SEC_2006',
    levelCode: params.levelCode,
    streamId: params.streamId,
    subjectId: params.subjectId,
    variantId: params.variantId,
    optional: params.optional,
    coefficient: params.coefficient,
    hours: params.hours,
    schemeId: params.schemeId,
    verification: {
      coefficient: params.coefVer ?? 'MULTI_SOURCE',
      hours: params.hoursVer ?? 'MULTI_SOURCE',
      scheme: params.schemeVer ?? 'MULTI_SOURCE',
    },
    sources: [
      SOURCES.DECISION_186_2006,
      SOURCES.IMG_MINISTRY_TABLE,
      SOURCES.FET_PDF,
      SOURCES.EDDIRASA_D20_REPORT,
    ],
    notes: params.notes,
  };
}

